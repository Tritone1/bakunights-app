function translated(pair: Translation, language: Exclude<AppLanguage, "en">) {
  return pair[language === "az" ? 0 : 1];
}

function translateDynamic(value: string, language: Exclude<AppLanguage, "en">): string | null {
  const rules: Array<[RegExp, (match: RegExpMatchArray) => Translation]> = [
    [/^(\d+) live offers?$/, (m) => [`${m[1]} canlı təklif`, `${m[1]} активных предложений`]],
    [/^(\d+) venues?$/, (m) => [`${m[1]} məkan`, `${m[1]} заведений`]],
    [/^(\d+) items?$/, (m) => [`${m[1]} məhsul`, `${m[1]} позиций`]],
    [/^(\d+) selected$/, (m) => [`${m[1]} seçilib`, `${m[1]} выбрано`]],
    [/^(\d+) points$/, (m) => [`${m[1]} xal`, `${m[1]} баллов`]],
    [/^(\d+) points!$/, (m) => [`${m[1]} xal!`, `${m[1]} баллов!`]],
    [/^(\d+) to next reward$/, (m) => [`Növbəti mükafata ${m[1]} xal`, `До следующей награды: ${m[1]}`]],
    [/^(\d+) lifetime points$/, (m) => [`Ümumi ${m[1]} xal`, `Всего баллов: ${m[1]}`]],
    [/^You earned (\d+) points!$/, (m) => [`${m[1]} xal qazandın!`, `Вы заработали ${m[1]} баллов!`]],
    [/^Your new balance is (\d+) points\.$/, (m) => [`Yeni balansın ${m[1]} xaldır.`, `Ваш новый баланс: ${m[1]} баллов.`]],
    [/^Member since (.+)$/, (m) => [`${m[1]} tarixindən üzvdür`, `Участник с ${m[1]}`]],
    [/^Offer ends (.+)$/, (m) => [`Təklif ${m[1]} bitir`, `Предложение заканчивается ${m[1]}`]],
    [/^Ends in (.+)$/, (m) => [`Bitməsinə ${m[1]}`, `До окончания ${m[1]}`]],
    [/^All venues · (\d+)$/, (m) => [`Bütün məkanlar · ${m[1]}`, `Все заведения · ${m[1]}`]],
    [/^Choose a route to (.+)\.$/, (m) => [`${m[1]} üçün marşrut seç.`, `Выберите маршрут до ${m[1]}.`]],
    [/^Covers all active items in (.+)$/, (m) => [`${m[1]} bölməsindəki bütün aktiv məhsulları əhatə edir`, `Включает все активные позиции в разделе ${m[1]}`]],
    [/^Navigate to (.+) in WhereToGo$/, (m) => [`WhereToGo-da ${m[1]} məkanına get`, `Построить маршрут до ${m[1]} в WhereToGo`]],
    [/^Save (.+)$/, (m) => [`${m[1]} yadda saxla`, `Сохранить ${m[1]}`]],
    [/^Remove (.+) from saved$/, (m) => [`${m[1]} yadda saxlanılanlardan sil`, `Удалить ${m[1]} из сохранённых`]],
    [/^Live · (.+)$/, (m) => [`Canlı · ${m[1]}`, `Сейчас · ${m[1]}`]],
  ];
  for (const [pattern, build] of rules) {
    const match = value.match(pattern);
    if (match) return translated(build(match), language);
  }
  return null;
}

function translateDateWords(value: string, language: Exclude<AppLanguage, "en">) {
  let result = value;
  for (const [word, pair] of Object.entries(dateWords)) result = result.replace(new RegExp(`\\b${word}\\b`, "g"), translated(pair, language));
  return result;
}

export function translateUiText(value: string, language: AppLanguage) {
  if (language === "en" || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const source = value.trim();
  const exact = messages[source];
  const result = exact ? translated(exact, language) : translateDynamic(source, language) ?? translateDateWords(source, language);
  return `${leading}${result}${trailing}`;
}
